package golden

// BehavioralSuite returns the Behavioral Golden 100 in stable order. Every
// scenario is a real Conversation driven through the production runtime; the
// Behavioral field adds family/style/tier metadata and dimension grading.
func BehavioralSuite() []Conversation {
	var out []Conversation
	out = append(out, behavioralConversation()...)
	out = append(out, behavioralMemory()...)
	out = append(out, behavioralActions()...)
	out = append(out, behavioralPermission()...)
	out = append(out, behavioralFailure()...)
	out = append(out, behavioralBrowser()...)
	out = append(out, behavioralComputer()...)
	out = append(out, behavioralRoutines()...)
	out = append(out, behavioralArtifacts()...)
	out = append(out, behavioralAdversarial()...)
	return out
}

